# Groups whose subcommands operate on a repository — gh shows the persistent
# `-R, --repo` flag on these (auth, for example, does not).
_REPO_SCOPED = {"repo", "issue", "pr", "label", "milestone", "run", "workflow", "release"}

_REPO_FLAG = "  -R, --repo [HOST/]OWNER/REPO   Select another repository using the [HOST/]OWNER/REPO format"


# ---- duck-typed introspection ----
def _is_group(cmd) -> bool:
    return isinstance(getattr(cmd, "commands", None), dict)


def _short(cmd) -> str:
    try:
        s = cmd.get_short_help_str(limit=200)
    except Exception:
        s = getattr(cmd, "short_help", None) or (getattr(cmd, "help", "") or "").strip().split("\n")[0]
    return s or ""


def _subcommands(group) -> dict:
    return {n: c for n, c in getattr(group, "commands", {}).items() if not getattr(c, "hidden", False)}


def _desc(parent_path: list[str], name: str, cmd) -> str:
    key = " ".join(parent_path[1:] + [name]) if parent_path[1:] else name
    return GH_DESC.get(key) or _short(cmd)


def _cmd_rows(parent_path: list[str], names_cmds) -> list[str]:
    rows = []
    for name, cmd in names_cmds:
        field = (name + ":").ljust(_NAME_COL)
        rows.append(f"  {field}{_desc(parent_path, name, cmd)}".rstrip())
    return rows


# ---- flag rendering (cobra/pflag style) ----
_METAVAR = {"TEXT": "string", "INTEGER": "int", "INT": "int", "FLOAT": "number"}


