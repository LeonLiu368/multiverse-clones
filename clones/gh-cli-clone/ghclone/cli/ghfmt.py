def _is_option(p) -> bool:
    return getattr(p, "param_type_name", "") == "option"


def _is_repo_opt(p) -> bool:
    return "--repo" in list(getattr(p, "opts", []))


def _opt_spec(opt) -> tuple[str, str]:
    """Return (left, desc) for a flag, e.g. ('-t, --title string', 'Supply a title')."""
    opts = list(getattr(opt, "opts", []))
    longs = sorted([o for o in opts if o.startswith("--")])
    shorts = sorted([o for o in opts if not o.startswith("--") and len(o) == 2])
    names = ", ".join(shorts + longs)
    left = ("  " + names) if shorts else ("      " + names)
    primary = longs[0] if longs else ""
    tmv, tdesc = _FLAG.get(primary, (None, None))
    is_flag = getattr(opt, "is_flag", False) or getattr(opt, "count", False)
    if not is_flag:
        tname = (getattr(getattr(opt, "type", None), "name", "") or "").upper()
        mv = tmv if tmv is not None else (getattr(opt, "metavar", None) or _METAVAR.get(tname, "string"))
        if mv:
            left = f"{left} {mv}"
    desc = tdesc if tdesc is not None else (getattr(opt, "help", "") or "")
    return left, desc


def _flag_block(opts) -> list[str]:
    pairs = [_opt_spec(o) for o in opts]
    if not pairs:
        return []
    maxleft = max(len(left) for left, _ in pairs)
    return [f"{left.ljust(maxleft)}   {d}".rstrip() for left, d in pairs]


def _real_opts(cmd) -> list:
    return [p for p in getattr(cmd, "params", [])
            if _is_option(p) and not getattr(p, "hidden", False) and not _is_repo_opt(p)]


def _has_repo(cmd) -> bool:
    return any(_is_repo_opt(p) for p in getattr(cmd, "params", []))


# ---- usage lines ----
def _usage(path: list[str], leaf: bool) -> str:
    base = " ".join(path)
    if leaf:
        return f"{base} [flags]"
    if path == ["gh"]:
        return f"{base} <command> <subcommand> [flags]"
    return f"{base} <command> [flags]"


# ---- help renderers ----
def _root_help(group) -> str:
    subs = _subcommands(group)
    out = ["Work seamlessly with GitHub from the command line.", "",
           "USAGE", "  " + _usage(["gh"], False), ""]
    for title, names in _ROOT_SECTIONS:
        present = [(n, subs[n]) for n in names if n in subs]
        if not present:
            continue
        out.append(title)
        out += _cmd_rows(["gh"], present)
        out.append("")
    out += ["FLAGS", "  --help      Show help for command", "  --version   Show gh version", ""]
    out += ["EXAMPLES", "  $ gh issue create",
            "  $ gh repo clone cli/cli", "  $ gh pr checkout 321", ""]
    out += _LEARN_MORE
    return "\n".join(out)


def _group_help(group, path: list[str]) -> str:
    subs = _subcommands(group)
    tagline = GH_TAGLINE.get(path[-1]) or (getattr(group, "help", "") or _short(group) or "").strip().split("\n\n")[0]
    out = [tagline, "", "USAGE", "  " + _usage(path, False), ""]
    out.append("AVAILABLE COMMANDS")
    out += _cmd_rows(path, sorted(subs.items()))
    out.append("")
    if path[-1] in _REPO_SCOPED:
        out += ["FLAGS", _REPO_FLAG, ""]
    out += ["INHERITED FLAGS", "  --help   Show help for command", ""]
    out += _LEARN_MORE
    return "\n".join(out)


def _leaf_help(cmd, path: list[str]) -> str:
    key = " ".join(path[1:])
    desc = (GH_TAGLINE.get(key) or GH_DESC.get(key)
            or (getattr(cmd, "help", "") or _short(cmd) or "")).strip()
    out = []
    if desc:
        out += [desc, "", ""]
    out += ["USAGE", "  " + _usage(path, True), ""]
    flags = _flag_block(_real_opts(cmd))
    if flags:
        out += ["FLAGS"] + flags + [""]
    inh = [("      --help", "Show help for command")]
    if _has_repo(cmd):
        inh.append(("  -R, --repo [HOST/]OWNER/REPO",
                    "Select another repository using the [HOST/]OWNER/REPO format"))
    maxleft = max(len(left) for left, _ in inh)
    out.append("INHERITED FLAGS")
    out += [f"{left.ljust(maxleft)}   {d}".rstrip() for left, d in inh]
    out.append("")
    out += _LEARN_MORE
    return "\n".join(out)


# ---- public: help dispatch ----
def try_help(root, argv: list[str]) -> bool:
    """If argv requests help (or names a group with no subcommand), print gh-style
    help to stdout and return True. Otherwise return False (let execution run)."""
    cmd = root
    path = ["gh"]
    i = 0
    while i < len(argv):
        tok = argv[i]
        if tok in ("--help", "-h"):
            _print_help(cmd, path)
            return True
        if _is_group(cmd):
            # walk ALL subcommands (incl. hidden) so even a hidden command's
            # --help renders gh-style; hidden ones are only kept out of listings.
            sub = getattr(cmd, "commands", {}).get(tok)
            if sub is not None:
                cmd, path, i = sub, path + [tok], i + 1
                continue
            return False  # unknown token at a group -> let execution raise it
        # reached a leaf: help only if --help is somewhere in the rest
        if "--help" in argv[i:] or "-h" in argv[i:]:
            _print_help(cmd, path)
            return True
        return False
    if _is_group(cmd):  # consumed all tokens sitting on a group -> gh prints help
        _print_help(cmd, path)
        return True
    return False


def _print_help(cmd, path: list[str]) -> None:
    if path == ["gh"] and _is_group(cmd):
        print(_root_help(cmd))
    elif _is_group(cmd):
        print(_group_help(cmd, path))
    else:
        print(_leaf_help(cmd, path))


# ---- public: error reformatting (cobra/gh phrasing) ----
def print_usage_error(e) -> None:
    ctx = getattr(e, "ctx", None)
    prog = ctx.command_path if ctx else "gh"
    try:
        msg = e.format_message()
    except Exception:
        msg = str(e)
    ename = type(e).__name__

    if ename == "NoSuchOption":
        flag = getattr(e, "option_name", None) or msg
        lines = [f"unknown flag: {flag}", ""]
        if ctx is not None:
            lines += [f"Usage:  {_cobra_usage(ctx)}", ""]
            fb = _flag_block(_real_opts(ctx.command))
            if fb:
                lines += ["Flags:"] + fb
        print("\n".join(lines), file=sys.stderr)
        return

    if msg.startswith("No such command"):
        bad = msg.split("'")[1] if "'" in msg else "?"
        group = ctx.command if ctx else None
        lines = [f'unknown command "{bad}" for "{prog}"', ""]
        if _is_group(group):
            lines += [f"Usage:  {_cobra_usage(ctx)}", "", "Available commands:"]
            lines += [f"  {n}" for n in sorted(_subcommands(group))]
        print("\n".join(lines), file=sys.stderr)
        return

    if "Missing argument" in msg or "Missing parameter" in msg:
        print("accepts 1 arg(s), received 0", file=sys.stderr)
        return

    if "Missing option" in msg:
        import re
        m = re.search(r"'(--?[\w-]+)'", msg)
        name = (m.group(1).lstrip("-") if m else "flag")
        print(f'required flag(s) "{name}" not set', file=sys.stderr)
        return

    print(f"gh: {msg}", file=sys.stderr)


def _cobra_usage(ctx) -> str:
    cmd = ctx.command
    path = ctx.command_path.split()
    return _usage(path, leaf=not _is_group(cmd))
