"""Render help/usage/errors in real `gh` (cobra) format, byte-for-byte.

`gh` is a Go/cobra binary; Click/Typer's native help and error output look
nothing like it (different USAGE line, section headers, flag table, error
phrasing). An agent that knows gh's output can spot the difference. This module
reproduces gh's exact layout so the surface is indistinguishable.

It operates on the Click command tree by DUCK TYPING (Typer vendors its own Click
fork as `typer._click`, so `isinstance(x, click.Group)` is unreliable). A command
is treated as a group iff it exposes a `.commands` dict.
"""

